import fs from "node:fs";
import path from "node:path";
import { lowContrast, overflowsHorizontally } from "../lib/checks.mjs";

const confirmWith = async (page, verb) => { const d = page.locator(".modal"); const b = d.getByRole("button", { name: verb, exact: true }); await b.waitFor(); await page.waitForFunction(el => !el.disabled, await b.elementHandle()); await b.click(); };
const openAddons = async page => {
  await page.keyboard.press("Control+k");
  const palette = page.getByRole("dialog", { name: "Actions" });
  await palette.waitFor();
  await page.keyboard.type("Add-ons");
  await page.waitForTimeout(200);
  await page.keyboard.press("Enter");
  await page.getByRole("dialog", { name: "Add-ons" }).waitFor();
};

const enableAddon = async page => {
  await openAddons(page);
  await page.getByRole("dialog", { name: "Add-ons" }).locator("li", { hasText: "task" }).first().getByRole("button", { name: "Enable" }).click();
  await confirmWith(page, "Enable");
  await page.waitForFunction(() => document.querySelector(".progress").getAttribute("aria-busy") === "false");
};


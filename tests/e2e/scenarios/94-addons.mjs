    const badge = page.locator(".ref .task-badge", { hasText: "#15607" }).first();
    t.ok("the number of the task has the title on hover, and is a link to the task", ((await badge.getAttribute("title")) || "").includes("Keep manual Order Date") && ((await badge.getAttribute("href")) || "").startsWith("https://odoo.example/"), String(await badge.getAttribute("title")));
    t.ok("...opened in a new tab, without opener or referrer", (await badge.getAttribute("target")) === "_blank" && /noopener/.test((await badge.getAttribute("rel")) || ""));
    t.ok("the branch of a task has the number of the task in the graph", (await page.locator(".ref .task-badge", { hasText: "#15607" }).count()) >= 1, await page.locator(".graph").first().innerText().catch(() => "no graph"));

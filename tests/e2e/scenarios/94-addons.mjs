    t.ok("nothing was made by the preview", !t.demo.git(["branch", "--format=%(refname:short)"]).split("\n").includes("feature/keep_manual_order_date"));
    await page.getByRole("button", { name: "Create the branch from the task" }).click();
    await page.waitForFunction(() => document.querySelector(".progress").getAttribute("aria-busy") === "false");
    await page.waitForFunction(() => /keep_manual_order_date/.test(document.body.innerText), null, { timeout: 8000 });
    t.ok("the branch is made, and it is the one checked out", t.demo.git(["branch", "--show-current"]) === "feature/keep_manual_order_date");
    t.ok("the branch remembers the task", t.demo.git(["config", "branch.feature/keep_manual_order_date.shuttle-ref-id"]) === "15607");
    await page.getByRole("tab", { name: "Ship" }).click();

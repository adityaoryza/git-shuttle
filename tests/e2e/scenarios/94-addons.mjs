    await page.getByRole("button", { name: "Clear filters" }).click();
    await page.getByText("Include done and closed").click();
    await page.getByText("3 of 3 tasks").waitFor();
    t.ok("done and closed tasks come only when asked", (await rows().count()) === 3);
    await page.getByLabel("All stages").selectOption("Done");
    await rows().first().click();
    t.ok("a task that is picked fills the field", (await page.getByPlaceholder("pick one above, or type the number or the link of the task").inputValue()) === "15001");
    await page.getByRole("button", { name: "Clear filters" }).click();
    await page.getByText("Include done and closed").click();
    t.ok("...the button waits for a task", (await page.getByRole("button", { name: "Create the branch from the task" }).count()) === 0);
